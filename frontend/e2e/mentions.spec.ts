import { randomUUID } from 'node:crypto';
import { expect, test } from '@playwright/test';
import { createProject, createTask, login } from './helpers';

test('mentions people with keyboard and pointer, in Comments and Internal Notes', async ({ page }) => {
  await login(page.request);
  const headers = { 'x-claude-task': '1' };
  const name = 'Mention Teammate';
  const response = await page.request.post('/api/v1/users', { headers, data: { displayName: name, email: `mention-${randomUUID()}@example.com` } });
  expect(response.status()).toBe(201);
  const { user } = await response.json();
  const project = await createProject(page.request);
  const task = await createTask(page.request, project, 'User mentions');
  await page.goto(`/t/${task.key}`);
  const editor = page.getByRole('textbox', { name: 'Comment', exact: true });
  await editor.fill('@');
  const list = page.getByRole('listbox', { name: 'Mention people' });
  await expect(list.getByRole('option', { name: /Mention Teammate/ })).toBeVisible();
  await editor.press('Escape');
  await expect(list).toBeHidden();
  await editor.fill('@mention');
  await expect(list.getByRole('option')).toHaveCount(1);
  await editor.press('Enter');
  await expect(editor).toContainText(`@${name}`);
  await expect(list).toBeHidden();
  const posted = page.waitForResponse(r => r.url().endsWith(`/tasks/${task.id}/comments`) && r.request().method() === 'POST');
  await editor.press('Enter');
  const comment = (await (await posted).json()).comment;
  expect(comment.body).toContain(`[@${name}](/users/${user.id})`);
  await expect(editor).toBeEmpty();
  await page.getByRole('switch', { name: 'Internal chat' }).click();
  await editor.fill('Please @mention');
  await list.getByRole('option', { name: /Mention Teammate/ }).click();
  await editor.press('Shift+Enter');
  await editor.pressSequentially('review');
  const internalPosted = page.waitForResponse(r => r.url().endsWith(`/tasks/${task.id}/comments`) && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  const internal = (await (await internalPosted).json()).comment;
  expect(internal.internal).toBe(true);
  expect(internal.body).toContain(`[@${name}](/users/${user.id})`);
  expect(internal.body).toContain('review');
  await editor.fill('someone@example.com');
  await expect(list).toBeHidden();
});
